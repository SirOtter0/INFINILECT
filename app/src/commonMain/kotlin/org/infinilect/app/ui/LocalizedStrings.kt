@Immutable
internal class LocalizedStrings(private val values: Map<UiText, String> = emptyMap(), val failed: Boolean = false) {
    fun withLoadFailure() = LocalizedStrings(values, failed = true)
    operator fun get(key: UiText): String = values[key] ?: key.fallback
    fun format(key: UiText, vararg args: Any): String {
        var result = get(key)
        args.forEachIndexed { index, value -> result = result.replace("%${index + 1}\$s", value.toString()) }
        return result
    }
    fun message(value: String): String = UiText.entries.firstOrNull { it.fallback.replace('’', '\'') == value.replace('’', '\'') }
        ?.let { get(it) } ?: get(UiText.GENERIC_TRANSLATION_ERROR)
}
internal val LocalAppStrings = staticCompositionLocalOf { LocalizedStrings() }
